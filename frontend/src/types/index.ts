export type StationType = 'master' | 'peripheral'

export type PredictLevel = 'Safe' | 'Low' | 'Medium' | 'High'

export type EventType = 'daily_heartbeat' | '15min_triggered_event'

export type SopStage = 'verify' | 'treat' | 'monitor' | 'closed'

export type ValidationOutcome = 'TP' | 'TN' | 'FP' | 'FN'

export type CaseStatus =
  | 'field_verified_infestation' // 1. Field verified termite found
  | 'treatment_start'            // 2. Treatment start
  | 'monitor'                    // 3. Monitor (~40d)
  | 'cleared'                    // 4. Clear (case resolved)
  | 'false_alarm'                // Alternative: False alarm cleared
  | 'routine_clean'              // Alternative: Routine check clean
  | 'terminated'                 // 5. Terminated / aborted early by technician

export type HumanVerificationStatus =
  | 'unverified'
  | 'field_verified_infestation'
  | 'treatment_start'
  | 'monitor'
  | 'verified_clean'
  | 'false_alarm'
  | 'terminated'

// ==========================================
// TABLE 1: Station Information Table (stations)
// Modifiable by user via GIS Map / Backend API
// ==========================================
export interface StationInfo {
  id: string // station_id (PK - unified station identifier e.g. ST-01)
  code?: string // optional alias for backward compatibility (matches id)
  name: string // descriptive name
  description: string // station details & notes
  type: StationType // 'master' | 'peripheral'
  coordinates: [number, number] // [lat, lng]
  plantationZone: string // e.g. Zone A - Center Core (empty if profile pending)
  treeTag: string // e.g. PW-RMB-0101 (empty if profile pending)
  isProfileComplete?: boolean // false if auto-registered from initial telemetry packet, awaiting user profile setup
  moistureThreshold: number // threshold % (e.g. 65.0%)
  samplingFrequencyMinutes: number // 15
  heartbeatIntervalHours: number // 24
  isSolarPowered: boolean
  installedAt: string
  // Multi-Event Temporal Health & Threat Assessment (Stored in Station Info Table)
  threatIndex: number // 0-100 continuous Infestation Threat Index (ITI - calculated strictly from data)
  threatLevel: PredictLevel // 'Safe' | 'Low' | 'Medium' | 'High' computed from rolling window
  windowHits: number // number of active detections in rolling evaluation window (e.g. 4/6)
  windowTotal: number // total cycles evaluated in rolling window (e.g. 6)
  windowSummary: string // human-readable status e.g. "4/6 active detections (90m window)"
  lastEvaluatedAt: string // timestamp of last temporal window evaluation
  // Human-in-the-Loop Ground Truth & SOP Lifecycle Status
  humanVerificationStatus: HumanVerificationStatus
  lastVerifiedAt?: string
  verifiedCleanAt?: string // Timestamp when station was verified clean (for "X days ago" display)
  verifiedBy?: string
  technicianNotes?: string
}

// ==========================================
// TABLE 3: Verification & SOP Cases Table (verification_cases)
// Dedicated table storing human audits & treatment lifecycle cases
// ==========================================
export interface VerificationCase {
  id: string // e.g. "CASE-2026-001"
  stationId: string
  stationCode: string
  stationName: string
  createdAt: string
  status: CaseStatus
  technician: string
  finding: 'termites_present' | 'clean_no_termites'
  probableCause?: string
  initialNotes: string
  
  // Multi-Stage Timeline Audit Trail
  verifiedAt?: string
  treatmentStartedAt?: string
  toxicantBatch?: string
  treatmentNotes?: string
  monitoredAt?: string
  monitoringNotes?: string
  clearedAt?: string
  clearedNotes?: string
  terminatedAt?: string
  terminatedNotes?: string
  
  // Model performance classification for Confusion Matrix
  validationOutcome?: ValidationOutcome
}

// ==========================================
// TABLE 2: Event Table (events / telemetry)
// Continuously updated via Gateway / Backend API
// Monitored in real-time by WebSocket
// ==========================================
export interface StationEvent {
  id: string // event_id (PK)
  stationId: string // station_id (FK)
  timestamp: string // ISO timestamp
  eventType: EventType // 'daily_heartbeat' | '15min_triggered_event'
  batteryLevel: number // 0-100%
  batteryVoltage: number // e.g. 3.7 - 4.2V
  soilMoisture: number // percentage 0-100%
  acousticScore: number | null // null when moisture < threshold (asleep)
  temperature: number // SHT31 ambient
  humidity: number // SHT31 relative humidity
  rssi: number // dBm
  snr: number // dB
  predictLevel: PredictLevel // generated by backend AI (Safe, Low, Medium, High)
  aiRiskScore: number // 0-100 predicted probability
  isMoistureTriggered: boolean
  mfccFeatures?: number[] // 13-band MFCC when acoustic is awake
  // Ground-Truth Performance Tag (Auto-populated from retroactive human verification)
  validationOutcome?: ValidationOutcome | null
  validatedAt?: string
  validatedBy?: string
  validationNotes?: string
}

// Composite Station for UI Convenience (StationInfo + Latest Event)
export interface Station extends StationInfo {
  status: 'online' | 'warning' | 'offline'
  latestEvent?: StationEvent
  // Mapped properties from latestEvent for clean UI access
  confidenceTier: PredictLevel
  operatingMode: 'dormant_heartbeat' | 'acoustic_triggered'
  isAcousticGated: boolean
  soilMoisture: number
  batteryLevel: number
  batteryVoltage: number
  temperature: number
  humidity: number
  activityScore: number | null
  aiRiskScore: number
  rssi: number
  snr: number
  lastSeen: string
  lastHeartbeatTime: string
  lastAcousticCaptureTime?: string
  nextExpectedTransmission: string
  mfccFeatures?: number[]
  zone: string // alias to plantationZone
}

